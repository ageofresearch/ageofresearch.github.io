import { readFile, writeFile } from 'node:fs/promises';
import { buildYachtGeometry } from '../../site/tidewater-rocha/assets/RochaYachtState-P5KwIGIl.js';
import { renderedParts } from '../../site/tidewater-rocha/mobile/stair-surfaces.js';
import { ownerContactBounds, ownerContactSize } from '../../site/tidewater-rocha/mobile/owner-contact-layout.js';
import { traceFloorContact } from './daylight-transfer.mjs';

const root = new URL('../../site/tidewater-rocha/', import.meta.url);
const data = JSON.parse(await readFile(new URL('rocha/luz-de-mar/model.json', root)));
const bytes = await readFile(new URL('rocha/luz-de-mar/model.bin', root));
const asset = { data, binary: bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) };
const model = buildYachtGeometry(asset, 0, { mtuEngines: false, seaStrainers: false });
model.asset = asset;
const triangles = [];
try {
  for (const part of renderedParts(model)) {
    const name = part.feature ?? '';
    if (!name.startsWith('suite ') || /sole|carpet|reveal|sill|gasket|glazing/i.test(name) ||
        part.glass || part.bounds[2] > 4.63) continue;
    for (let i = 0; i < part.indices.length; i += 3) {
      const triangle = Array.from(part.indices.slice(i, i + 3), index =>
        Array.from(part.vertices.slice(index * 6, index * 6 + 3)));
      if (triangle.some(point => point[2] > 3.962)) triangles.push(triangle);
    }
  }
} finally {
  model.dispose();
}

// Sample just above the tops of the oak sole and the rug.
const image = traceFloorContact(triangles, ownerContactBounds, 3.962, ownerContactSize);
const runs = [];
for (let i = 0; i < image.length;) {
  const value = image[i];
  let count = 1;
  while (count < 255 && i + count < image.length && image[i + count] === value) count++;
  runs.push(count, value);
  i += count;
}
const encoded = Buffer.from(runs).toString('base64').match(/.{1,100}/g).join('\n');
const output = process.argv[2] ?? new URL('mobile/owner-contact-data.js', root);
await writeFile(output, '// Generated by scripts/yacht-geometry/bake-owner-contact.mjs.\n' +
  'export default `\n' + encoded + '\n`;\n');
console.log(`${triangles.length} caster triangles, ${image.length} contact texels`);
