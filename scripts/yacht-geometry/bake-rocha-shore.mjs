// Radial shoreline samples of the mapped lake, in yacht-local metres. The
// distant bank elevation is illustrative; only the waterline is mapped.
import {readFile,writeFile} from 'node:fs/promises';
import {findBerth} from '../../site/tidewater-rocha/assets/RochaYachtState-P5KwIGIl.js';
const root=new URL('../../site/tidewater-rocha/',import.meta.url);
const world=JSON.parse(await readFile(new URL('rocha/luz-de-mar/berth.json',root)));
const berth=findBerth(world),water=world.waterBodies.find(w=>w.id===berth.lakeId);
const [bx,,bz]=berth.position,cy=Math.cos(berth.yaw),sy=Math.sin(berth.yaw);
const radii=Array.from({length:72},(_,i)=>{
  const a=i*Math.PI/36,dx=Math.cos(a)*sy+Math.sin(a)*cy,dz=Math.cos(a)*cy-Math.sin(a)*sy;
  let result=Infinity;
  for(const outline of [water.outer,...water.holes])for(let j=0;j<outline.length;j++){
    const [x,z]=outline[j],next=outline[(j+1)%outline.length],ex=next[0]-x,ez=next[1]-z,det=dx*ez-dz*ex;
    if(Math.abs(det)<1e-9)continue;
    const t=((x-bx)*ez-(z-bz)*ex)/det,u=((x-bx)*dz-(z-bz)*dx)/det;
    if(t>0&&u>=0&&u<=1)result=Math.min(result,t);
  }
  if(!Number.isFinite(result))throw Error('Open lake boundary at '+i);
  return +result.toFixed(2);
});
// Cut the lake out of the hull at its actual flotation plane. Sampling just
// inside the outer shell keeps a wet joint along the sides and the cabin dry.
const model=JSON.parse(await readFile(new URL('rocha/luz-de-mar/model.json',root)));
const binary=await readFile(new URL('rocha/luz-de-mar/model.bin',root));
const hull=model.meshes.find(m=>m.id==='HULL_HUL_001');
const v=new Float32Array(binary.buffer,binary.byteOffset+hull.vByte,hull.vCount*6);
const indices=new Uint16Array(binary.buffer,binary.byteOffset+model.vertexBytes+hull.iByte,hull.iCount);
const segments=[];
for(let i=0;i<indices.length;i+=3){
  const verts=Array.from(indices.slice(i,i+3),id=>Array.from(v.subarray(id*6,id*6+3)));
  const ends=[];
  for(let k=0;k<3;k++){
    const a=verts[k],b=verts[(k+1)%3];
    if((a[2]<2.01)===(b[2]<2.01))continue;
    const t=(2.01-a[2])/(b[2]-a[2]);
    ends.push([(a[0]+t*(b[0]-a[0])-18)*35.23/36,(a[1]+t*(b[1]-a[1]))*7.47/7.6]);
  }
  if(ends.length===2)segments.push(ends);
}
const hullRadii=radii.map((_,i)=>{
  const a=2*Math.PI*i/radii.length,dx=Math.cos(a),dy=Math.sin(a);let radius=0;
  for(const [[x,y],[X,Y]] of segments){
    const ex=X-x,ey=Y-y,det=dx*ey-dy*ex;
    if(Math.abs(det)<1e-8)continue;
    const t=(x*ey-y*ex)/det,u=(x*dy-y*dx)/det;
    if(t>0 && u>=0 && u<=1)radius=Math.max(radius,t);
  }
  if(radius<2)throw Error('Open hull section '+i);
  return +(radius-.06).toFixed(3);
});
await writeFile(new URL('mobile/rocha-waterline.js',root),
  '// Generated by bake-rocha-shore.mjs from the berth, lake and Rocha hull.\nexport const waterline='+JSON.stringify(radii)+';\nexport const hullWaterline='+JSON.stringify(hullRadii)+';\n');
