// Radial shoreline samples of the mapped lake, in yacht-local metres. The
// distant bank elevation is illustrative; only the waterline is mapped.
import {readFile,writeFile} from 'node:fs/promises';
import {findBerth} from '../../site/tidewater-rocha/assets/RochaYachtState-P5KwIGIl.js';
const root=new URL('../../site/tidewater-rocha/',import.meta.url);
const world=JSON.parse(await readFile(new URL('rocha/luz-de-mar/berth.json',root)));
const berth=findBerth(world),water=world.waterBodies.find(w=>w.id===berth.lakeId);
const [bx,,bz]=berth.position,cy=Math.cos(berth.yaw),sy=Math.sin(berth.yaw);
const radii=Array.from({length:72},(_,i)=>{
  const a=i*Math.PI/36,dx=Math.cos(a)*sy+Math.sin(a)*cy,dz=Math.cos(a)*cy-Math.sin(a)*sy;
  let result=Infinity;
  for(const outline of [water.outer,...water.holes])for(let j=0;j<outline.length;j++){
    const [x,z]=outline[j],next=outline[(j+1)%outline.length],ex=next[0]-x,ez=next[1]-z,det=dx*ez-dz*ex;
    if(Math.abs(det)<1e-9)continue;
    const t=((x-bx)*ez-(z-bz)*ex)/det,u=((x-bx)*dz-(z-bz)*dx)/det;
    if(t>0&&u>=0&&u<=1)result=Math.min(result,t);
  }
  if(!Number.isFinite(result))throw Error('Open lake boundary at '+i);
  return +result.toFixed(2);
});
await writeFile(new URL('mobile/rocha-waterline.js',root),'// Generated by bake-rocha-shore.mjs from the shared berth and lake outline.\nexport const waterline='+JSON.stringify(radii)+';\n');
